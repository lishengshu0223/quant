def _match(code, table):
    """对巨潮码做 2 位步长最长前缀匹配（优先全码精确）"""
    for plen in range(len(code), 3, -2):
        hit = table.get(code[:plen])
        if hit:
            return hit
    return None


def get_fields(type_codes):
    """给定巨潮原始码串或主码，返回命中类别的字段信息 dict；未命中返回 None

    输入可为 classify() 输出中的 cninfo_type_code（主码），或原始 "||" 码串。
    """
    if not type_codes:
        return None
    if "||" in str(type_codes):
        from .announcement_type_map import select_primary
        code = select_primary(type_codes)
    else:
        code = str(type_codes).strip()
    if not code:
        return None
    return _match(code, ANNOUNCEMENT_FIELDS)


def format_prompt_section(fields):
    """把字段信息格式化为提示词片段（中文），未命中时给出兜底指引"""
    if not fields:
        return ("该公告类别未收录于字段表：请根据公告标题与正文自行识别核心要素"
                "（主体、金额/数量、时间、原因、后续安排），缺失信息标注“未披露”。")
    lines = [f"【{fields['name']}】"
             f"（法规依据：{fields['sources']}）", "必有字段："]
    lines += [f"  - {f}" for f in fields["required"]]
    lines += ["可能有字段："]
    lines += [f"  - {f}" for f in fields["optional"]]
    lines += ("说明：必字段缺失时返回“未披露”；可字段按正文实际出现情况抽取，"
              "不得臆造。")
    return "\n".join(lines)
