def select_primary(type_codes):
    """从 "||" 连接的巨潮码串中选取主码

    规则：剔除组 0101 的市场/文书辅助码后，取最长（最具体）的业务码；
    长度相同取字典序最小以保证稳定。全部为辅助码或空串时返回 ""。
    """
    codes = [c.strip() for c in str(type_codes or "").split("||") if c.strip()]
    codes = [c for c in codes if not c.startswith("0101")]
    if not codes:
        return ""
    return sorted(codes, key=lambda c: (-len(c), c))[0]


def _longest_prefix_match(code, table):
    """按 2 位步长做最长前缀匹配，返回匹配到的值（无匹配返回 ""）"""
    for plen in range(len(code), 2, -2):
        val = table.get(code[:plen])
        if val:
            return val
    return ""


def classify(type_codes):
    """静态查表：巨潮码串 → 巨潮层级分类 + 证监会分类（返回 dict，键见 CLASSIFY_COLUMNS）

    未知主码也能给出层级码（纯字符串切分）和一级组映射；
    仅对应层级的中文名与证监会二级在查不到时留空。
    """
    out = {col: "" for col in CLASSIFY_COLUMNS}
    primary = select_primary(type_codes)
    out["cninfo_type_code"] = primary
    if not primary:
        return out

    # 巨潮层级：一级组(4位) ~ 四级(10位)，逐级切分查名
    out["cninfo_l1_code"] = primary[:4]
    out["cninfo_l1_name"] = CN_L1_NAMES.get(primary[:4], "")
    if len(primary) >= 6:
        out["cninfo_l2_code"] = primary[:6]
        out["cninfo_l2_name"] = CN_L2_NAMES.get(primary[:6], "")
    if len(primary) >= 8:
        out["cninfo_l3_code"] = primary[:8]
        out["cninfo_l3_name"] = CN_L3_NAMES.get(primary[:8], "")
    if len(primary) >= 10:
        out["cninfo_l4_code"] = primary[:10]
        out["cninfo_l4_name"] = CN_L4_NAMES.get(primary[:10], "")
    # 最细分类名称：优先精确匹配，回退到最长已知前缀
    out["cninfo_leaf_name"] = _longest_prefix_match(primary, CN_CODE_NAMES)

    # 证监会分类：一级全覆盖，二级仅精确对应时给出
    out["csrc_l1_code"] = _longest_prefix_match(primary, CN_TO_CSRC_L1)
    out["csrc_l1_name"] = CSRC_L1.get(out["csrc_l1_code"], "")
    out["csrc_l2_code"] = _longest_prefix_match(primary, CN_TO_CSRC_L2)
    out["csrc_l2_name"] = CSRC_L2.get(out["csrc_l2_code"], "")
    return out
