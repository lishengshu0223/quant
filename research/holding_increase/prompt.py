# 公告筛选提示词 - 筛选高管/大股东增持预告
FILTER_ANNOUNCEMENT_PROMPT = """
你是一个专业的证券分析师，擅长筛选上市公司公告。请根据以下公告标题列表，筛选出符合条件的公告。

## 筛选条件
筛选出当天发布的关于【高管或大股东增持预告】的公告。

### 判断标准：
1. **增持预告**：公告内容涉及高管或大股东计划/拟增持公司股票的预告、预案、方案
   - 典型标题包括："关于控股股东/高管增持公司股份的预告"、"XX增持公司股份的公告"、"拟增持公司股份"等
2. **排除已实施的增持**：公告仅为报告已经完成的增持进度/结果的，不算（如"XX已增持XX万股"的完成性公告）
3. **同步公告也算**：如果增持实施与公告同时发生（当日公告即增持完成），这种也算，因为这是该增持事件最早的公告
4. **主体限制**：必须是高管（董事、监事、高级管理人员等）或大股东（持股5%以上股东、控股股东、实际控制人等）的增持

### 复合公告处理规则（重要）：
当公告标题同时包含"完成/实施完成"和"拟继续增持/新计划"时：
- **保留**：如果公告包含新的增持计划要素（如新的数量/金额、期限、方式等），即使同时报告了旧计划完成
- **排除**：如果只是报告旧计划完成，没有新的增持计划（如"XX增持计划完成公告"、"关于XX已完成增持的公告"）
- 判断技巧：关注标题中是否有"拟"、"将"、"计划"等表示未来动作的词汇

### 需要排除的情况：
- 股权激励相关公告（标题含"股权激励"、"激励计划"、"员工持股"等，属于股权激励范畴，不是高管主动增持）
- 纯粹的完成公告（标题仅含"完成增持"、"增持进展公告"，且无新计划）
- 股份回购相关公告（回购不是高管/大股东主动增持）

## 输出格式
请返回JSON格式，包含以下字段：
- "is_increase_announcement": true或false，表示是否有高管/大股东增持预告公告
- "relevant_indices": 一个数组，包含符合条件的公告的序号（从1开始计数）。如果没有符合条件的公告，则返回空数组[]
- "reason": 简要说明判断理由

公告标题列表：
{titles}

请严格按照JSON格式返回，不要添加任何其他文字。
"""

# 结构化分析提示词 - 分析增持公告的详细信息
STRUCTURED_ANALYSIS_PROMPT = """
你是一个专业的证券分析师，请仔细阅读以下高管/大股东增持公告的完整文本，提取结构化信息。

## 提取要求
请以JSON格式返回以下字段。**必须严格按照指定格式返回，不得添加任何额外字段或文字。**

### 必须返回的字段：
1. **增持主体**: "高管"或"大股东"
2. **增持标的**: "金额"或"数量"
3. **增持金额下限**: 最低增持金额（元），如果以数量计则填null
4. **增持金额上限**: 最高增持金额（元），如果公告中未提及上限则填null
5. **增持数量下限**: 最低增持数量（股），如果以金额计则填null
6. **增持数量上限**: 最高增持数量（股），如果公告中未提及上限则填null
7. **增持价格上限**: 增持价格上限（元/股），如"不超过XX元"，没有则填null
8. **增持价格下限**: 增持价格下限（元/股），如"不低于XX元"，没有则填null
9. **增持目的**: 分析增持目的，选项为："高管主动增持"、"大股东主动增持"、"回购计划（稳定股价）"、"其他被动增持"、"其他"
10. **增持期限**: 以月份整数形式保存，6个月返回6，1年返回12，未提及返回null
11. **资金来源**: 可能值："自有"、"自筹"、"金融机构专项贷"、"其他"。如有多种则用|分隔。如为"其他"，先写"其他"再用括号补充类型，如"其他（员工持股计划专项资金）"
12. **增持方式**: 可能值："集中竞价"、"大宗交易"、"协议转让"、"其他"。如有多种则用|分隔。如为"其他"，先写"其他"再用括号补充类型
13. **不减持承诺月份**: 高管承诺增持完成后多少个月内不减持。法律法规默认锁定期不算，仅额外承诺的部分。无承诺返回null

### 复合公告处理规则（重要）：
当公告同时包含"已完成的增持报告"和"新的增持计划"时：
- **只提取新的增持计划信息**，忽略已完成部分
- 判断依据：关注公告中"拟"、"将"、"新计划"等表述所对应的增持内容
- 例如：公告先报告旧计划完成100万股，再宣布新计划拟增持200万股，应提取200万股相关信息

### 已增持部分作为下限的规则（重要）：
当公告属于"同步公告"或"披露义务公告"——即增持人当日已增持部分股票并同步公告，同时披露后续增持安排：
- 如果公告明确给出了后续增持的金额/数量下限，则正常提取
- 如果公告**未明确给出后续增持下限**，但提到了**本次已增持的金额或数量**，则将已增持部分作为下限
  - 例如："截至本公告日，已增持50万元" → 增持金额下限=500000元
  - 例如："本次已增持10万股" → 增持数量下限=100000股
- 如果公告同时提到了已增持部分和后续计划总额，已增持部分可视为下限，总额视为上限
  - 例如："已增持100万元，拟累计增持不低于300万元" → 下限=1000000，上限=3000000

### 重要规则：
- 金额单位统一为"元"，万元需转换为元（如100万元=1000000元）
- 数量单位统一为"股"，万股需转换为股（如100万股=1000000股）
- 价格单位统一为"元/股"
- 如果公告中既有金额又有数量，请两者都提取
- "增持价格上限"通常表述为"不超过XX元"或"不高于XX元"
- "增持价格下限"通常表述为"不低于XX元"或"不低于该价格"

## 输出格式
请返回合法的JSON格式。

公告文本：
{text}

请严格按照JSON格式返回，不要添加任何其他文字。
"""
